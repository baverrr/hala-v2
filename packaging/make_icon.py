"""Generate hala/data/hala.svg, the app icon: a hala fruit on a 64x64 view box.

    python3 packaging/make_icon.py

Hexagonal keys are wrapped onto a near-round oval like a sphere, each with a bulge highlight
and a woody tip, coloured from green by the stalk to red at the base; behind it a crown of
long, drooping pandanus blades.
"""

import itertools
import math
from pathlib import Path

CX, CY, RX, RY = 32.0, 40.0, 21.0, 20.5   # fruit: nearly round
HEX_R = 5.9                               # key size in "flat" grid units


def warp(x, y):
    """Flat grid point -> point on the oval, squeezing toward the rim like a sphere."""
    dx, dy = (x - CX) / RX, (y - CY) / RY
    d = math.hypot(dx, dy)
    if d == 0:
        return CX, CY
    k = math.sin(min(d, 1.0) * math.pi / 2) / d
    return CX + dx * k * RX, CY + dy * k * RY


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def hexcol(c):
    return "#{:02x}{:02x}{:02x}".format(*c)


# Ripening from the stalk down: green-yellow top, orange middle, red base.
STOPS = [(0.0, (112, 158, 52)), (0.28, (196, 186, 52)), (0.5, (236, 150, 40)),
         (0.75, (230, 92, 34)), (1.0, (192, 36, 32))]


def colour(t):
    t = max(0.0, min(1.0, t))
    for (t0, c0), (t1, c1) in itertools.pairwise(STOPS):
        if t <= t1:
            return lerp(c0, c1, (t - t0) / (t1 - t0))
    return STOPS[-1][1]


keys = []
w = math.sqrt(3) * HEX_R
row = 0
y = CY - RY * 1.6
while y < CY + RY * 1.6:
    off = (w / 2) if row % 2 else 0
    x = CX - RX * 1.6 + off
    while x < CX + RX * 1.6:
        d = math.hypot((x - CX) / RX, (y - CY) / RY)
        if d < 1.08:
            corners = []
            for i in range(6):
                a = math.radians(60 * i + 30)
                px, py = x + HEX_R * 0.93 * math.cos(a), y + HEX_R * 0.93 * math.sin(a)
                corners.append(warp(px, py))
            cx_, cy_ = warp(x, y)
            keys.append((d, cx_, cy_, corners))
        x += w
    y += HEX_R * 1.5
    row += 1

out = []
out.append('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">')
out.append('  <!-- A hala fruit (Pandanus tectorius): a ball of wedge-shaped keys, green by\n'
           '       the stalk and ripening to orange and red below, under a crown of drooping\n'
           '       pandanus leaves. Generated by packaging/make_icon.py; edit that instead. -->')
out.append('  <defs>')
out.append(f'    <clipPath id="fruit"><ellipse cx="{CX}" cy="{CY}" rx="{RX}" ry="{RY}"/>'
           '</clipPath>')
out.append('    <radialGradient id="shade" cx="38%" cy="40%" r="65%">'
           '<stop offset="0" stop-color="#fff" stop-opacity="0.35"/>'
           '<stop offset="0.55" stop-color="#fff" stop-opacity="0"/>'
           '<stop offset="1" stop-color="#3a0a05" stop-opacity="0.55"/></radialGradient>')
out.append('    <radialGradient id="bulge" cx="38%" cy="32%" r="70%">'
           '<stop offset="0" stop-color="#fff" stop-opacity="0.45"/>'
           '<stop offset="0.5" stop-color="#fff" stop-opacity="0"/>'
           '<stop offset="1" stop-color="#2a0800" stop-opacity="0.35"/></radialGradient>')
out.append('    <linearGradient id="leaf" x1="0" y1="1" x2="0" y2="0">'
           '<stop offset="0" stop-color="#2f6b2a"/><stop offset="1" stop-color="#5fae4a"/>'
           '</linearGradient>')
out.append('  </defs>')

# Leaf crown: long strap-like pandanus blades that arch up and droop out to the sides,
# drawn behind the fruit as tapering ribbons along cubic curves.
def ribbon(p0, p1, p2, p3, width, n=24):
    def at(t):
        u = 1 - t
        return (u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
                u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1])
    pts = [at(i / n) for i in range(n + 1)]
    left, right = [], []
    for i, (x, y) in enumerate(pts):
        ax, ay = pts[max(i - 1, 0)]
        bx, by = pts[min(i + 1, n)]
        dx, dy = bx - ax, by - ay
        ln = math.hypot(dx, dy) or 1
        w = width * (1 - i / n) ** 0.8
        left.append((x - dy / ln * w, y + dx / ln * w))
        right.append((x + dy / ln * w, y - dx / ln * w))
    poly = left + right[::-1]
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in poly) + "Z"
    mid = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts[:-3])
    return d, mid


top = (CX, CY - RY + 2)
BLADES = [  # (control 1, control 2, tip, half-width), back to front
    ((24, 10), (8, 6), (2, 22), 3.0),
    ((40, 10), (56, 6), (62, 22), 3.0),
    ((26, 4), (14, 0), (6, 10), 3.2),
    ((38, 4), (50, 0), (58, 10), 3.2),
    ((29, 2), (22, -2), (17, 3), 3.0),
    ((35, 2), (42, -2), (47, 3), 3.0),
    ((32, 6), (31, 0), (30, 1), 2.6),
]
for c1, c2, tip, width in BLADES:
    d, mid = ribbon(top, c1, c2, tip, width)
    out.append(f'  <path d="{d}" fill="url(#leaf)" stroke="#1f4a1c" stroke-width="0.6" '
               'stroke-linejoin="round"/>')
    out.append(f'  <path d="{mid}" fill="none" stroke="#a9d98a" stroke-width="0.45" '
               'opacity="0.6"/>')
out.append(f'  <path d="M{CX - 2.5} {CY - RY + 3}h5l-1 -5h-3z" fill="#4b3a1a"/>')  # stalk

# The fruit: dark gaps between the keys, each key a hexagon with a lighter face and a
# dark woody tip in the middle.
out.append(f'  <ellipse cx="{CX}" cy="{CY}" rx="{RX}" ry="{RY}" fill="#5a1c0c"/>')
out.append('  <g clip-path="url(#fruit)">')
for d, kx, ky, corners in sorted(keys, key=lambda k: k[0], reverse=True):
    t = (ky - (CY - RY)) / (2 * RY)
    c = colour(t)
    pts = " ".join(f"{px:.2f},{py:.2f}" for px, py in corners)
    out.append(f'    <polygon points="{pts}" fill="{hexcol(c)}" stroke="#6b2a10" '
               'stroke-width="0.55" stroke-linejoin="round"/>')
    # The key's woody tip: a smaller hexagon, olive on green keys, brown on ripe ones;
    # it shrinks toward the rim, where the keys turn away.
    shrink = 0.5 * max(0.35, 1 - d * 0.6)
    tip_pts = " ".join(f"{kx + (px - kx) * shrink:.2f},{ky + (py - ky) * shrink:.2f}"
                       for px, py in corners)
    tip = lerp(lerp(c, (60, 80, 30), 0.55), (90, 50, 20), t)
    out.append(f'    <polygon points="{pts}" fill="url(#bulge)"/>')  # each key bulges
    out.append(f'    <polygon points="{tip_pts}" fill="{hexcol(tip)}" stroke-linejoin="round"/>')
out.append(f'    <ellipse cx="{CX}" cy="{CY}" rx="{RX}" ry="{RY}" fill="url(#shade)"/>')
out.append('  </g>')
out.append(f'  <ellipse cx="{CX}" cy="{CY}" rx="{RX}" ry="{RY}" fill="none" stroke="#4a1608" '
           'stroke-width="0.9"/>')
out.append('</svg>')
(Path(__file__).resolve().parent.parent / "hala" / "data" / "hala.svg").write_text(
    "\n".join(out) + "\n")
